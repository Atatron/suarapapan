"""Inspect every shipped bitmap and make reviewable contact sheets + an audit table.

python tools/audit_katalog.py [--sheets path/to/sprite-sheets-39-2026-10-16]
"""
import argparse
import hashlib
import html
import json
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'web/src/scene/katalog.json'
OUT = ROOT / 'docs/audit/assets'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sheets', type=Path)
    args = parser.parse_args()
    assets = json.loads(CATALOG.read_text(encoding='utf-8'))
    OUT.mkdir(parents=True, exist_ok=True)
    errors, rows, groups = [], [], {}
    for a in assets:
        p = ROOT / 'web/public' / a['path'].lstrip('/')
        try:
            with Image.open(p) as im:
                im.load()
                rgba = im.convert('RGBA')
                box = rgba.getchannel('A').getbbox()
                if not box:
                    errors.append(f"Empty bitmap: {a['path']}")
                rows.append({**a, 'width': im.width, 'height': im.height, 'alpha_bbox': box,
                             'sha256': hashlib.sha256(p.read_bytes()).hexdigest()})
        except Exception as e:
            errors.append(f"{a['path']}: {e}")
        group = f"sheet-{a['sheet']:02d}" if a.get('sheet') else f"legacy-{a['kind']}"
        groups.setdefault(group, []).append(a)
    source_checks = []
    if args.sheets:
        checksums = json.loads((ROOT / 'tools/aset_tampilan_39_checksums.json').read_text(encoding='utf-8'))
        for name, expected in checksums.items():
            p = args.sheets / name
            actual = hashlib.sha256(p.read_bytes()).hexdigest() if p.exists() else None
            source_checks.append({'file': name, 'matches': actual == expected})
            if actual != expected:
                errors.append(f'Source checksum mismatch: {name}')
    previews = []
    for group, items in groups.items():
        for offset in range(0, len(items), 12):
            chunk = items[offset:offset+12]
            canvas = Image.new('RGB', (1200, 900), '#16302a')
            draw = ImageDraw.Draw(canvas)
            for i, a in enumerate(chunk):
                x, y = (i % 4) * 300, (i // 4) * 300
                with Image.open(ROOT / 'web/public' / a['path'].lstrip('/')) as im:
                    thumb = im.convert('RGBA')
                    thumb.thumbnail((270, 235))
                    canvas.paste(thumb, (x + (300-thumb.width)//2, y+10+(235-thumb.height)//2), thumb)
                draw.text((x+10, y+252), a['id'], fill='white')
                draw.text((x+10, y+273), f"{a['kind']} | sheet {a.get('sheet')} frame {a.get('frame')}", fill='#c8d9c8')
            name = f'{group}-{offset//12+1}.jpg'
            canvas.save(OUT / name, quality=85)
            previews.append(name)
    report = {'counts': {kind: len([a for a in assets if a['kind'] == kind]) for kind in ('obj','tempat','latar')},
              'catalog_sha256': hashlib.sha256(CATALOG.read_bytes()).hexdigest(),
              'source_checks': source_checks, 'errors': errors, 'assets': rows, 'contact_sheets': previews}
    (OUT / 'audit.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    header = ['# Complete asset audit', '', 'Generated by `python tools/audit_katalog.py`. Frame indexes are zero based; each original sheet has four columns and three rows.', '',
              f"Runtime: **410 object/subject/prop sprites, 127 place sprites, 32 backgrounds**. Checked {len(source_checks)} original sheet hashes. Bitmap errors: {len(errors)}.", '',
              '## Contact sheets', '']
    header += [f'- [{name}]({name})' for name in previews]
    header += ['', '## Every runtime asset', '', '| ID | Kind | Source English label | Sheet/frame | File |', '|---|---|---|---|---|']
    for a in assets:
        source = (a.get('source') or 'legacy').replace('|','/')
        header.append(f"| {a['id']} | {a['kind']} | {source} | {a.get('sheet') or 'legacy'} / {a.get('frame') if a.get('frame') is not None else '-'} | [image](../../../web/public{a['path']}) |")
    (OUT / 'README.md').write_text('\n'.join(header)+'\n', encoding='utf-8')
    cards = ''.join(f'''<article data-search="{html.escape(' '.join([a['id'],a['kind'],*a['aliases']]))}"><img loading="lazy" src="../../../web/public{a['path']}" alt="{html.escape(a['name'])}"><b>{html.escape(a['id'])}</b><span>{a['kind']} · sheet {a.get('sheet') or 'legacy'} · frame {a.get('frame')}</span><small>{html.escape(a.get('source') or a['name'])}</small></article>''' for a in assets)
    (OUT / 'index.html').write_text('''<!doctype html><meta charset="utf-8"><title>SuaraPapan asset audit</title><style>
body{font:16px system-ui;background:#f6f3e9;color:#16302a;margin:32px}header{position:sticky;top:0;background:#f6f3e9;padding:12px 0}input{width:min(600px,90%);padding:12px;font:inherit}main{display:grid;grid-template-columns:repeat(auto-fill,minmax(220px,1fr));gap:16px}article{background:white;padding:12px;border-radius:12px;display:flex;flex-direction:column;gap:6px}img{width:100%;height:180px;object-fit:contain;background:#16302a;border-radius:8px}span,small{color:#55685b}[hidden]{display:none}</style><header><h1>SuaraPapan · complete asset catalog</h1><p>410 subjects/objects/props · 127 places · 32 backgrounds. Search Indonesian or English.</p><input type="search" placeholder="Search: anak kursi roda, wheelchair, ruang guru…" aria-label="Search assets"><p id="count">569 assets</p></header><main>'''+cards+'''</main><script>document.querySelector('input').addEventListener('input',e=>{const q=e.target.value.toLowerCase().replace(/[^a-z0-9]+/g,'-');let n=0;document.querySelectorAll('article').forEach(a=>{a.hidden=!a.dataset.search.includes(q);if(!a.hidden)n++});document.querySelector('#count').textContent=n+' assets'})</script>''', encoding='utf-8')
    print(json.dumps({'counts': report['counts'], 'sheet_hashes': len(source_checks), 'errors': errors, 'contact_sheets': len(previews)}, ensure_ascii=False))
    if errors:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
